let currentLang = localStorage.getItem('te_privacy_lang') || 'en';

function applyLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('te_privacy_lang', lang);

  const isAr = lang === 'ar';
  document.documentElement.lang = isAr ? 'ar' : 'en';
  document.documentElement.dir = isAr ? 'rtl' : 'ltr';
  document.body.className = isAr ? 'lang-ar' : 'lang-en';

  const strings = translations[lang];
  document.title = strings.pageTitle;

  for (const [id, value] of Object.entries(strings)) {
    const el = document.getElementById(id);
    if (el) {
      el.innerHTML = value;
    }
  }
}

document.addEventListener('DOMContentLoaded', () => {
  applyLanguage(currentLang);

  const langBtn = document.getElementById('langToggleBtn');
  if (langBtn) {
    langBtn.addEventListener('click', () => {
      const nextLang = currentLang === 'en' ? 'ar' : 'en';
      applyLanguage(nextLang);
    });
  }

  // Active pill highlight on scroll
  const sections = document.querySelectorAll('main section');
  const navPills = document.querySelectorAll('.nav-pill');

  window.addEventListener('scroll', () => {
    let current = '';
    const scrollPos = window.scrollY + 120;

    sections.forEach(section => {
      if (scrollPos >= section.offsetTop) {
        current = section.getAttribute('id');
      }
    });

    navPills.forEach(pill => {
      pill.classList.remove('active');
      if (pill.getAttribute('href') === `#${current}`) {
        pill.classList.add('active');
      }
    });
  });
});
